'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const tracker=require('../app/src/main/assets/storm_tracking.js');
const rect=(left,bottom,right,top)=>[[[left,bottom],[right,bottom],[right,top],[left,top],[left,bottom]]];
const warning=(event,id,geometry)=>({type:'Feature',id,properties:{event,id,areaDesc:'Test County',expires:'2026-10-24T07:00:00Z'},geometry});
const polygon=warning('Tornado Warning','one',{type:'Polygon',coordinates:rect(-87,34,-86,35)});
assert.equal(tracker.featureMiles(polygon,34.5,-86.5),0);
assert.ok(tracker.featureMiles(polygon,34.5,-87.5)>20);
assert.ok(tracker.featureMiles(polygon,34.5,-87.5)<40);
assert.equal(tracker.nearby([polygon],34.5,-86.5)[0].inside,true);
assert.equal(tracker.nearby([polygon],34.5,-105).length,0);
assert.equal(tracker.nearby([polygon],NaN,-86).length,0);
const hole=warning('Flash Flood Warning','hole',{type:'Polygon',coordinates:[...rect(-87,34,-86,35),...rect(-86.6,34.4,-86.4,34.6)]});
assert.equal(tracker.featureMiles(hole,34.3,-86.7),0);
assert.ok(tracker.featureMiles(hole,34.5,-86.5)>0);
const multi=warning('Severe Thunderstorm Warning','multi',{type:'MultiPolygon',coordinates:[rect(-95,38,-94,39),rect(-87,34,-86,35)]});
assert.equal(tracker.featureMiles(multi,34.5,-86.5),0);
assert.equal(tracker.nearby([warning('Heat Advisory','heat',polygon.geometry)],34.5,-86.5).length,0);
assert.equal(tracker.nearby([polygon,polygon,multi,hole],34.5,-86.5,100,2).length,2);
assert.equal(tracker.nearby([warning('Tornado Warning','none',null)],34.5,-86.5).length,0);
const html=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/radar.html'),'utf8');
assert.ok(html.includes('src="storm_tracking.js"')&&html.includes('id="nearbyThreats"'));
assert.ok(html.includes('function updateTrackedThreatList()')&&html.includes('fetchTrackedThreats()'));
const start=html.indexOf('<script>'),end=html.lastIndexOf('</script>');
assert.ok(start>=0&&end>start);
new Function(html.slice(start+8,end));
console.log('Smart Storm Tracking geometry and radar JavaScript checks passed');
